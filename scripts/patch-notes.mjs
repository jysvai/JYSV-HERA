// Patch notes live in docs/patch-notes/{en,ko}/vX.Y.Z.md, one file per release and
// language. This script turns them into what GitHub shows:
//   node scripts/patch-notes.mjs body v0.2.1 > body.md   release text (English, then Korean, then downloads)
//   node scripts/patch-notes.mjs index                  rewrite docs/patch-notes/README.md
//   node scripts/patch-notes.mjs check v0.2.1           fail unless both languages exist
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const dir = path.join(root, 'docs', 'patch-notes')
const REPO = 'https://github.com/jysvai/JYSV-HERA'
const [command, tag] = process.argv.slice(2)

function read(lang, version) {
  const file = path.join(dir, lang, `${version}.md`)

  return fs.existsSync(file) ? fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n').trim() : null
}

/** Versions with notes, newest first. */
function versions() {
  const names = new Set()

  for (const lang of ['en', 'ko']) {
    for (const name of fs.existsSync(path.join(dir, lang)) ? fs.readdirSync(path.join(dir, lang)) : []) {
      if (/^v\d+\.\d+\.\d+\.md$/.test(name)) names.add(name.slice(0, -3))
    }
  }

  const parts = version => version.slice(1).split('.').map(Number)

  return [...names].sort((a, b) => {
    const [x, y] = [parts(a), parts(b)]

    return y[0] - x[0] || y[1] - x[1] || y[2] - x[2]
  })
}

/**
 * The notes without their own `# title` line (the release has its title already).
 * Paths relative to docs/patch-notes/<lang>/ become absolute, since a release page has no folder.
 */
const body = text =>
  text
    .replace(/^# .*\n+/, '')
    .replace(/(src="|\]\()\.\.\/\.\.\/images\//g, `$1https://raw.githubusercontent.com/jysvai/JYSV-HERA/main/docs/images/`)
    .replace(/(href="|\]\()\.\.\/\.\.\/(en|ko)\//g, `$1${REPO}/blob/main/docs/$2/`)

function downloads(version) {
  const v = version.slice(1)
  const file = name => `\`JYSV-HERA-${v}-${name}\``

  return [
    '### Download · 다운로드',
    '',
    '| OS | File · 파일 |',
    '|---|---|',
    `| Windows 10 / 11 (x64) | ${file('win-x64.exe')} (installer · 설치) · ${file('win-x64.zip')} (portable · 휴대용) |`,
    `| macOS 12+ Apple Silicon | ${file('mac-arm64.dmg')} |`,
    `| macOS 12+ Intel | ${file('mac-x64.dmg')} |`,
    `| Ubuntu 20.04+ / Debian 11+ | ${file('linux-amd64.deb')} |`,
    `| Rocky / Alma / RHEL 9+, Fedora | ${file('linux-x86_64.rpm')} |`,
    `| Any Linux (x64) · 그 밖의 Linux | ${file('linux-x86_64.AppImage')} · ${file('linux-x64.tar.gz')} |`,
    '',
    'Every file was built on its own OS and passed a self-test there (real terminal, the `hera` CLI, the window). Checksums: `SHA256SUMS.txt`.',
    '모든 파일은 각 OS 에서 빌드하고 그 자리에서 자체 시험(실제 터미널 · `hera` CLI · 창)을 통과했습니다. 체크섬은 `SHA256SUMS.txt`.',
    '',
    '- **Windows:** not code-signed yet; if SmartScreen asks, *More info → Run anyway*. · 코드 서명 전이라 SmartScreen 이 막으면 *추가 정보 → 실행*.',
    '- **macOS:** not notarized; the first time, right-click the app → *Open*. · 공증 전이라 처음 한 번은 우클릭 → *열기*.'
  ].join('\n')
}

function releaseBody(version) {
  const en = read('en', version)
  const ko = read('ko', version)

  if (!en || !ko) throw new Error(`missing patch notes for ${version}: docs/patch-notes/${!en ? 'en' : 'ko'}/${version}.md`)

  return [
    `<p align="center"><img src="https://raw.githubusercontent.com/jysvai/JYSV-HERA/main/docs/images/hero.jpg" alt="JYSV HERA" width="760"></p>`,
    '',
    body(en),
    '',
    '---',
    '',
    '## 한국어',
    '',
    // The English part already shows the pictures; a release page should not load them twice.
    body(ko)
      .replace(/<table>(?:(?!<\/table>)[\s\S])*?<img[\s\S]*?<\/table>\n*/g, '')
      .replace(/^<p align="center"><img [^\n]*<\/p>\n*/gm, ''),
    '',
    '---',
    '',
    downloads(version),
    '',
    `All patch notes · 전체 패치노트: [docs/patch-notes](${REPO}/tree/main/docs/patch-notes)`
  ].join('\n')
}

function index() {
  const rows = versions().map(version => {
    const title = (read('en', version) || '').match(/^# .*?(\d{4}-\d{2}-\d{2})/)?.[1] || ''
    const summary = (read('en', version) || '').split('\n').find(line => line && !line.startsWith('#')) || ''
    const link = lang => (read(lang, version) ? `[${lang === 'en' ? 'English' : '한국어'}](${lang}/${version}.md)` : '—')

    return `| [${version}](${REPO}/releases/tag/${version}) | ${title} | ${summary.replace(/\|/g, '\\|')} | ${link('en')} · ${link('ko')} |`
  })

  return [
    '# Patch notes · 패치노트',
    '',
    'One file per release and language. A release on GitHub is written from these files, and editing one updates that release (`.github/workflows/patch-notes.yml`).',
    '',
    '릴리스마다 언어별로 파일이 하나씩 있습니다. GitHub 릴리스 본문은 이 파일로 만들어지고, 파일을 고치면 그 릴리스도 갱신됩니다.',
    '',
    '| Version | Date | Summary | Notes |',
    '|---|---|---|---|',
    ...rows,
    '',
    '<!-- Generated by `node scripts/patch-notes.mjs index`. -->',
    ''
  ].join('\n')
}

if (command === 'body' && tag) process.stdout.write(`${releaseBody(tag)}\n`)
else if (command === 'check' && tag) releaseBody(tag)
else if (command === 'index') fs.writeFileSync(path.join(dir, 'README.md'), index())
else if (command === 'versions') process.stdout.write(`${versions().join('\n')}\n`)
else {
  console.error('usage: node scripts/patch-notes.mjs body <tag> | check <tag> | index | versions')
  process.exit(1)
}
