// Shell resolution and boot files for HERA terminals. Every shell gets the
// user's shortcuts (aliases) and `hera` on PATH without touching the user's own
// profile files: PowerShell dot-sources a generated script, cmd loads a doskey
// macro file, bash uses --rcfile, zsh a ZDOTDIR shim, fish --init-command.
import fs from 'node:fs'
import path from 'node:path'

import type { Shortcut } from '../shared/types'

import { binDir, findOnPath, home, isWin, subDir } from './paths'

export interface ShellSpec {
  kind: 'powershell' | 'pwsh' | 'cmd' | 'bash' | 'zsh' | 'fish' | 'sh' | 'other'
  command: string
  args: string[]
  env: Record<string, string>
  name: string
}

const VALID_NAME = /^[A-Za-z_][A-Za-z0-9_-]*$/

function windowsPowerShell(): string | null {
  const root = process.env.SystemRoot || process.env.windir || 'C:\\Windows'
  const builtin = path.join(root, 'System32', 'WindowsPowerShell', 'v1.0', 'powershell.exe')

  return fs.existsSync(builtin) ? builtin : findOnPath('powershell.exe')
}

function gitBash(): string | null {
  const candidates = [
    path.join(process.env.ProgramFiles || 'C:\\Program Files', 'Git', 'bin', 'bash.exe'),
    path.join(process.env.LOCALAPPDATA || '', 'Programs', 'Git', 'bin', 'bash.exe')
  ]

  return candidates.find(candidate => fs.existsSync(candidate)) || null
}

/** Resolve a shell preference ('auto', a kind, or an absolute path) to an executable. */
export function resolveShell(pref: string | undefined): { kind: ShellSpec['kind']; command: string } {
  const choice = (pref || 'auto').trim()

  if (choice && choice !== 'auto') {
    const byKind: Record<string, () => string | null> = {
      powershell: () => (isWin ? windowsPowerShell() : findOnPath('pwsh')),
      pwsh: () => findOnPath(isWin ? 'pwsh.exe' : 'pwsh'),
      cmd: () => (isWin ? process.env.COMSPEC || 'cmd.exe' : null),
      bash: () => (isWin ? gitBash() : findOnPath('bash') || '/bin/bash'),
      gitbash: () => gitBash(),
      zsh: () => findOnPath('zsh') || (fs.existsSync('/bin/zsh') ? '/bin/zsh' : null),
      fish: () => findOnPath('fish')
    }
    const resolved = byKind[choice]?.() ?? (path.isAbsolute(choice) && fs.existsSync(choice) ? choice : findOnPath(choice))

    if (resolved) {
      return { kind: kindOf(resolved), command: resolved }
    }
  }

  if (isWin) {
    // Windows PowerShell 5.1 starts noticeably faster than pwsh 7 and is always
    // present; pwsh is used when the user picks it.
    const command = windowsPowerShell() || process.env.COMSPEC || 'cmd.exe'

    return { kind: kindOf(command), command }
  }

  const login = process.env.SHELL && fs.existsSync(process.env.SHELL) ? process.env.SHELL : null
  const command = login || ['/bin/zsh', '/bin/bash', '/bin/sh'].find(candidate => fs.existsSync(candidate)) || '/bin/sh'

  return { kind: kindOf(command), command }
}

function kindOf(command: string): ShellSpec['kind'] {
  const name = path.basename(command).toLowerCase()

  if (name.startsWith('pwsh')) return 'pwsh'
  if (name.startsWith('powershell')) return 'powershell'
  if (name.startsWith('cmd')) return 'cmd'
  if (name.startsWith('bash')) return 'bash'
  if (name.startsWith('zsh')) return 'zsh'
  if (name.startsWith('fish')) return 'fish'
  if (name === 'sh' || name === 'dash') return 'sh'

  return 'other'
}

// ---- generated shortcut files

// PowerShell also treats the typographic single quotes as quote characters;
// a smart quote pasted from Word/IME would otherwise end the string early.
function psQuote(value: string) {
  return `'${value.replace(/['\u2018\u2019\u201A\u201B]/g, quote => quote + quote)}'`
}

function shQuote(value: string) {
  return `'${value.replace(/'/g, `'\\''`)}'`
}

export function writeShortcutFiles(shortcuts: Shortcut[]): void {
  const dir = subDir('shell')
  const valid = shortcuts.filter(shortcut => VALID_NAME.test(shortcut.name) && shortcut.command.trim())
  const header = 'Generated by JYSV HERA - edit shortcuts in the app.'

  const ps = [`# ${header}`]

  for (const { name, command } of valid) {
    // Built-in aliases (gc, gl, sl, ...) shadow functions; drop them first.
    ps.push(`if (Test-Path ${psQuote(`alias:${name}`)}) { Remove-Item ${psQuote(`alias:${name}`)} -Force -ErrorAction SilentlyContinue }`)
    ps.push(`function global:${name} { ${command} @args }`)
  }

  // BOM: Windows PowerShell 5.1 reads BOM-less scripts in the ANSI code page.
  fs.writeFileSync(path.join(dir, 'aliases.ps1'), `\ufeff${ps.join('\r\n')}\r\n`, 'utf8')

  const doskey = valid.map(({ name, command }) => `${name}=${command} $*`)
  fs.writeFileSync(path.join(dir, 'aliases.doskey'), `${doskey.join('\r\n')}\r\n`, 'utf8')

  const sh = [`# ${header}`]

  for (const { name, command } of valid) {
    sh.push(`unalias ${name} 2>/dev/null`)
    sh.push(`${name}() { ${command} "$@"; }`)
  }

  fs.writeFileSync(path.join(dir, 'aliases.sh'), `${sh.join('\n')}\n`, 'utf8')

  const fish = [`# ${header}`]

  for (const { name, command } of valid) {
    fish.push(`function ${name}; ${command} $argv; end`)
  }

  fs.writeFileSync(path.join(dir, 'aliases.fish'), `${fish.join('\n')}\n`, 'utf8')

  writeShellShims(dir)
}

function writeShellShims(dir: string) {
  const bin = binDir()
  const aliasesSh = path.join(dir, 'aliases.sh')

  // bash: --rcfile replaces ~/.bashrc, so source the user's files first.
  const bashrc = [
    '# JYSV HERA bash init',
    '[ -f /etc/profile ] && [ -n "$HERA_LOGIN" ] && . /etc/profile',
    'if [ -f ~/.bash_profile ] && [ -n "$HERA_LOGIN" ]; then . ~/.bash_profile; elif [ -f ~/.bashrc ]; then . ~/.bashrc; fi',
    `export PATH=${shQuote(bin)}:"$PATH"`,
    `. ${shQuote(aliasesSh)}`
  ]
  fs.writeFileSync(path.join(dir, 'bashrc'), `${bashrc.join('\n')}\n`, 'utf8')

  // zsh: point ZDOTDIR at shims that source the user's real dotfiles.
  const zdot = path.join(dir, 'zsh')
  fs.mkdirSync(zdot, { recursive: true })
  const userDot = '${HERA_USER_ZDOTDIR:-$HOME}'
  const shim = (file: string, tail = '') =>
    [
      `# JYSV HERA zsh shim (${file})`,
      `HERA_SHIM_ZDOTDIR="$ZDOTDIR"`,
      `ZDOTDIR="${userDot}"`,
      `[ -f "$ZDOTDIR/${file}" ] && . "$ZDOTDIR/${file}"`,
      `HERA_USER_ZDOTDIR="$ZDOTDIR"`,
      `ZDOTDIR="$HERA_SHIM_ZDOTDIR"`,
      tail
    ].join('\n')
  fs.writeFileSync(path.join(zdot, '.zshenv'), `${shim('.zshenv')}\n`, 'utf8')
  fs.writeFileSync(path.join(zdot, '.zprofile'), `${shim('.zprofile')}\n`, 'utf8')
  fs.writeFileSync(
    path.join(zdot, '.zshrc'),
    `${shim('.zshrc', `export PATH=${shQuote(bin)}:"$PATH"\n. ${shQuote(aliasesSh)}`)}\n`,
    'utf8'
  )
  fs.writeFileSync(
    path.join(zdot, '.zlogin'),
    `${shim('.zlogin', '# hand ZDOTDIR back to the user for child shells\nZDOTDIR="$HERA_USER_ZDOTDIR"')}\n`,
    'utf8'
  )
}

/** Build the spawn spec for an interactive shell with HERA's boot applied. */
export function buildShellSpec(pref: string | undefined, loadProfile: boolean): ShellSpec {
  const { kind, command } = resolveShell(pref)
  const dir = subDir('shell')
  const bin = binDir()
  const env: Record<string, string> = {}
  const name = path.basename(command)

  if (!fs.existsSync(path.join(dir, 'aliases.ps1'))) {
    writeShortcutFiles([])
  }

  switch (kind) {
    case 'powershell':
    case 'pwsh': {
      const script = [
        // UTF-8 console so Korean (and every other script) survives native
        // command output captured by PowerShell and by agents' child shells.
        '[Console]::OutputEncoding = [Text.Encoding]::UTF8',
        '$OutputEncoding = [Text.Encoding]::UTF8',
        `$env:Path = ${psQuote(bin)} + [IO.Path]::PathSeparator + $env:Path`,
        `. ${psQuote(path.join(dir, 'aliases.ps1'))}`
      ].join('; ')
      const encoded = Buffer.from(script, 'utf16le').toString('base64')
      const args = ['-NoLogo', '-NoExit']

      if (!loadProfile) {
        args.push('-NoProfile')
      }

      if (isWin) {
        args.push('-ExecutionPolicy', 'Bypass')
      }

      args.push('-EncodedCommand', encoded)

      return { kind, command, args, env, name }
    }

    case 'cmd': {
      const boot = path.join(dir, 'boot.cmd')
      fs.writeFileSync(
        boot,
        [
          '@echo off',
          'chcp 65001 >nul',
          `set "PATH=${bin};%PATH%"`,
          `doskey /macrofile="${path.join(dir, 'aliases.doskey')}"`,
          '@echo on'
        ].join('\r\n'),
        'utf8'
      )

      return { kind, command, args: ['/k', boot], env, name }
    }

    case 'bash': {
      env.HERA_LOGIN = isWin ? '' : '1'

      return { kind, command, args: ['--rcfile', path.join(dir, 'bashrc'), '-i'], env, name }
    }

    case 'zsh': {
      env.HERA_USER_ZDOTDIR = process.env.ZDOTDIR || home
      env.ZDOTDIR = path.join(dir, 'zsh')

      return { kind, command, args: ['-il'], env, name }
    }

    case 'fish': {
      const init = `set -gx PATH ${shQuote(bin)} $PATH; source ${shQuote(path.join(dir, 'aliases.fish'))}`

      return { kind, command, args: ['-il', '-C', init], env, name }
    }

    default:
      return { kind, command, args: isWin ? [] : ['-i'], env, name }
  }
}

/** Shell-appropriate way to set env vars inline before a command (for typed commands). */
export function envPrefix(kind: ShellSpec['kind'], vars: Record<string, string>): string {
  const entries = Object.entries(vars)

  if (!entries.length) {
    return ''
  }

  switch (kind) {
    case 'powershell':
    case 'pwsh':
      return `${entries.map(([key, value]) => `$env:${key}=${psQuote(value)}`).join('; ')}; `
    case 'cmd':
      return `${entries.map(([key, value]) => `set "${key}=${value}"`).join(' & ')} & `
    case 'fish':
      return `${entries.map(([key, value]) => `set -gx ${key} ${shQuote(value)}`).join('; ')}; `
    default:
      return `${entries.map(([key, value]) => `export ${key}=${shQuote(value)}`).join('; ')}; `
  }
}

/** Quote one argument for the given shell. */
export function quoteArg(kind: ShellSpec['kind'], value: string): string {
  switch (kind) {
    case 'powershell':
    case 'pwsh':
      return psQuote(value)
    case 'cmd':
      return `"${value.replace(/"/g, '""')}"`
    default:
      return shQuote(value)
  }
}
